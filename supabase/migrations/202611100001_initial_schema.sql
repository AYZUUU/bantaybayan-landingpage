create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null unique,
  first_name text not null default '',
  last_name text not null default '',
  contact_number text not null default '',
  role text not null default 'citizen'
    check (role in ('citizen', 'responder', 'admin', 'superadmin')),
  status text not null default 'pending',
  password_reset_required boolean not null default false,
  station text,
  is_verified boolean not null default false,
  avatar_path text,
  id_photo_path text,
  legacy_avatar_url text,
  legacy_id_photo_url text,
  legacy_user_id bigint,
  legacy_account_source text,
  push_token text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_legacy_account_idx
  on public.profiles (legacy_account_source, legacy_user_id)
  where legacy_user_id is not null;

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles (id) on delete set null,
  reporter_name text,
  contact_number text,
  emergency_type text,
  accident_level text,
  description text,
  latitude double precision,
  longitude double precision,
  image_path text,
  legacy_image_path text,
  legacy_report_id bigint unique,
  status text not null default 'Pending',
  assigned_responder_id uuid references public.profiles (id) on delete set null,
  municipality text,
  province text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reports_latitude_valid check (latitude between -90 and 90),
  constraint reports_longitude_valid check (longitude between -180 and 180)
);

create index if not exists reports_user_created_idx
  on public.reports (user_id, created_at desc);
create index if not exists reports_status_created_idx
  on public.reports (status, created_at desc);
create index if not exists reports_assigned_responder_idx
  on public.reports (assigned_responder_id, created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
before update on public.profiles
for each row execute function public.touch_updated_at();

drop trigger if exists reports_touch_updated_at on public.reports;
create trigger reports_touch_updated_at
before update on public.reports
for each row execute function public.touch_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_role text;
begin
  requested_role := 'citizen';

  insert into public.profiles (
    id,
    email,
    first_name,
    last_name,
    contact_number,
    role,
    status,
    station,
    id_photo_path
  )
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    coalesce(new.raw_user_meta_data ->> 'contact_number', ''),
    requested_role,
    'pending',
    nullif(new.raw_user_meta_data ->> 'station', ''),
    nullif(new.raw_user_meta_data ->> 'id_photo_path', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.has_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.status = 'active'
      and p.role = any (allowed_roles)
  );
$$;

