create policy "Owners and staff can view reports"
on public.reports for select to authenticated
using (
  user_id = (select auth.uid())
  or public.has_role(array['responder', 'admin', 'superadmin'])
);

drop policy if exists "Staff can update reports" on public.reports;
create policy "Staff can update reports"
on public.reports for update to authenticated
using (
  public.has_role(array['admin', 'superadmin'])
  or (
    public.has_role(array['responder'])
    and assigned_responder_id = (select auth.uid())
  )
)
with check (
  public.has_role(array['admin', 'superadmin'])
  or (
    public.has_role(array['responder'])
    and assigned_responder_id = (select auth.uid())
  )
);

