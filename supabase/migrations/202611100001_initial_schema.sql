create or replace function public.reset_report_id_sequence()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  max_id bigint;
begin
  if auth.role() <> 'service_role' then
    raise exception 'service role required';
  end if;

  select max(id) into max_id from public.reports;
  perform setval(
    pg_get_serial_sequence('public.reports', 'id'),
    coalesce(max_id, 1),
    max_id is not null
  );
end;
$$;

revoke all on function public.reset_report_id_sequence() from public, anon, authenticated;
grant execute on function public.reset_report_id_sequence() to service_role;
